public class classroomSeating {

    public static void main(String[] args) {

        for (int row = 1; row <= 3; row++) {
            
            for (int seat = 1; seat <= 4; seat++) {

                System.out.println("Row: " + row + "-Seat: " + seat);
            }

            System.out.println();
        }
    }
}